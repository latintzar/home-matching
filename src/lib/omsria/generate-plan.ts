/**
 * Step 2: Generate Editing Plan
 * 
 * Takes Step 1's prompt and generates editing prompts (text-based, like original manual process)
 */

import { callGeminiRest } from '@/lib/gemini-rest-client';

export interface GeneratePlanInput {
  imageBase64: string;
  imageMimeType: string;
  step1Prompt: string; // Prompt generated by Step 1
}

export interface SimplePlan {
  decision: 'POSSIBLE' | 'PARTIALLY_POSSIBLE' | 'NOT_POSSIBLE';
  reasoning: string;
  prompts: Array<{
    id: number;
    text: string;
  }>;
}

export interface GeneratePlanOutput {
  plan: SimplePlan;
}

// Simple JSON schema for structured output
const planResponseSchema = {
  type: 'object',
  properties: {
    Decision: { 
      type: 'string', 
      enum: ['POSSIBLE', 'PARTIALLY_POSSIBLE', 'NOT_POSSIBLE'] 
    },
    Reasoning: { type: 'string' },
    Prompts: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
          id: { type: 'number' },
          text: { type: 'string' }
            },
        required: ['id', 'text']
          }
        }
      },
  required: ['Decision', 'Reasoning', 'Prompts']
};

/**
 * Generate OMSRIA editing plan using Step 1's prompt
 * Uses structured JSON output for reliability
 */
export async function generateEditingPlan(
  input: GeneratePlanInput
): Promise<GeneratePlanOutput> {
  const { imageBase64, imageMimeType, step1Prompt } = input;

  // Step 2: Use Step 1's output + exact template
  // Extract space names from Step 1's output to validate
  const spaceNamesInPrompt = step1Prompt.match(/\[SPACE_NAME\]|visible in it|on the/gi) ? [] : 
    step1Prompt.match(/(?:has|visible|and)\s+([A-Z][a-zA-Z\s]+?)(?:\s+visible|\s+in\s+it|,|$)/gi) || [];
  
  const fullPrompt = `${step1Prompt}

CRITICAL: When referencing spaces in your reasoning and prompts, use ONLY the exact space names mentioned in the description above. Do NOT use generic terms like "Living Room", "Kitchen", "Bedroom" unless they are explicitly mentioned in the description above. Do NOT infer space names from the image.

Your goal is to make the areas mentioned above to be not visible, in an organic way, by picking the smartest out of the following options:

1. Closing a door

2. Drawing curtains

3. Panning the camera left or right by up to 30 degrees.

4. A combination of the above

Decide which strategy is best.

When drawing curtains:
- Only use curtains on windows, glass doors, balcony/terrace doors, floor-to-ceiling glazed openings, or similar openings where curtains would naturally be used.
- It is okay to add simple curtains even if they are not currently visible, as long as they are placed in a realistic location (over glass or a large opening), not on a solid wall.
- Do not hang curtains on plain solid walls or on purely structural openings where curtains would be unnatural.

Naturally, don't close a door where there isn't already a door. The context for this work is being able to work with the images to show before-and-after renovation images, and with our current image editing technology, it is difficult to achieve consistency in elements that show up in multiple images, hence the goal to do organic edits to the images to have simpler images to work with, which only show ONE space clearly.

If one of the mentioned areas would inevitably be visible, please say NOT POSSIBLE, and say why. If only some of the areas are possible to be obscured, say PARTIALLY POSSIBLE.

Please output prompts for gemini-2.5-flash-image to perform the edits, which it would do one at a time. The prompts should be clear, efficient, and explicit. If you choose camera movement as one of the options, it should be the first in the list of prompt(s) you write.`;

  // Call Gemini Pro with structured JSON output
  const result = await callGeminiRest(fullPrompt, {
    model: 'gemini-2.5-pro',
    temperature: 0.2,
    topP: 0.8,
    topK: 40,
    maxOutputTokens: 6096,
    thinkingConfig: {
      thinkingBudget: -1
    },
    responseMimeType: 'application/json',
    responseSchema: planResponseSchema,
    images: [{
      mimeType: imageMimeType as 'image/jpeg' | 'image/png' | 'image/webp' | 'image/gif',
      data: imageBase64
    }]
  });

  if (!result.success || !result.text) {
    throw new Error(`Failed to generate editing plan: ${result.error || 'Unknown error'}`);
  }

  // Parse JSON response
  let cleaned = result.text.trim()
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim();

  cleaned = cleaned.replace(/,(\s*[}\]])/g, '$1');

  let parsed: {
    Decision: 'POSSIBLE' | 'PARTIALLY_POSSIBLE' | 'NOT_POSSIBLE';
    Reasoning: string;
    Prompts: Array<{ id: number; text: string }>;
  };
  
  try {
    parsed = JSON.parse(cleaned);
  } catch (parseError: any) {
    throw new Error(`Failed to parse editing plan: ${parseError.message}. Response: ${cleaned.substring(0, 500)}`);
  }

  // Validate structure
  if (!parsed.Decision || !parsed.Prompts || !Array.isArray(parsed.Prompts)) {
    throw new Error(`Invalid editing plan structure: ${JSON.stringify(parsed)}`);
  }

  // Allow empty prompts only if Decision is NOT_POSSIBLE
  // Validate: NOT_POSSIBLE should have no prompts
  if (parsed.Decision === 'NOT_POSSIBLE' && parsed.Prompts.length > 0) {
    console.warn(`⚠️  Decision is NOT_POSSIBLE but ${parsed.Prompts.length} prompts were generated. Clearing prompts.`);
    parsed.Prompts = [];
  }

  // Log NOT_POSSIBLE decisions for debugging
  if (parsed.Decision === 'NOT_POSSIBLE') {
    console.log(`⚠️  OMSRIA Plan: NOT_POSSIBLE decision made`);
    console.log(`   Reasoning: ${parsed.Reasoning || 'No reasoning provided'}`);
    console.log(`   Step 1 prompt length: ${step1Prompt.length} chars`);
    console.log(`   Step 1 prompt preview: ${step1Prompt.substring(0, 300)}${step1Prompt.length > 300 ? '...' : ''}`);
  }

  // Validate: POSSIBLE/PARTIALLY_POSSIBLE should have prompts
  if (parsed.Prompts.length === 0 && parsed.Decision !== 'NOT_POSSIBLE') {
    throw new Error(`No prompts found in response. Response: ${cleaned.substring(0, 500)}`);
  }

  // Log empty prompts for debugging
  if (parsed.Prompts.length === 0) {
    console.log(`⚠️  OMSRIA Plan: Empty prompts array`);
    console.log(`   Decision: ${parsed.Decision}`);
    console.log(`   Reasoning: ${parsed.Reasoning || 'No reasoning provided'}`);
  }

  // Validate prompts don't contain forbidden words (add, place, install, etc.)
  // Check for whole words only (not substrings like "fireplace" containing "place")
  const forbiddenWords = ['add', 'place', 'install', 'put', 'insert', 'create', 'build', 'construct'];
  for (const prompt of parsed.Prompts) {
    const promptLower = prompt.text.toLowerCase();
    // Use word boundary regex to match whole words only
    for (const word of forbiddenWords) {
      const wordBoundaryRegex = new RegExp(`\\b${word}\\b`, 'i');
      if (wordBoundaryRegex.test(promptLower)) {
        throw new Error(`Prompt contains forbidden word "${word}": ${prompt.text.substring(0, 100)}. Prompts can only close existing doors/curtains or pan camera.`);
      }
    }
  }

  return {
    plan: {
      decision: parsed.Decision,
      reasoning: parsed.Reasoning || '',
      prompts: parsed.Prompts
    }
  };
}

