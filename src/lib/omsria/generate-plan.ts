export interface EditingStep {
  Step_ID: number;
  Type: 'Camera Angle Change' | 'Physical Change (Curtains)' | 'Physical Change (Door)' | 'Combination';
  Target_Area_Hidden: string;
  Prompt: string;
}

export interface OMSRIAPlan {
  Process_Name: string;
  Decision: 'POSSIBLE' | 'PARTIALLY_POSSIBLE' | 'NOT_POSSIBLE';
  Reasoning: string;
  Areas_Targeted: string[];
  Areas_Hidden: string[];
  Areas_Unavoidable: string[];
  Editing_Plan: {
    Strategy: string;
    Steps: EditingStep[];
  };
}
