-- Add natural language fields to photo_pov table
ALTER TABLE photo_pov 
  ADD COLUMN IF NOT EXISTS nl_overview TEXT,
  ADD COLUMN IF NOT EXISTS aesthetic_notes TEXT,
  ADD COLUMN IF NOT EXISTS expected_consistency JSONB;

-- Update comments
COMMENT ON COLUMN photo_pov.nl_overview IS 'Natural language overview of the photo: camera position, main focus, spatial relationships';
COMMENT ON COLUMN photo_pov.aesthetic_notes IS 'Aesthetic observations: lighting, mood, color palette, textures visible in this photo';
COMMENT ON COLUMN photo_pov.expected_consistency IS 'Cross-photo consistency expectations: { hard_match_element_ids: [...], soft_match_element_ids: [...] }';

-- Update visible_in_room structure comment to include new fields
COMMENT ON COLUMN photo_pov.visible_in_room IS 'Enhanced visibility tracking: [{ element, element_id, element_type, surface, prominence, visibility_status, nl_note, confidence, occlusion_detail, lexical_variants, notes }]';

-- Create room_consistency table for room-level consistency preferences
CREATE TABLE IF NOT EXISTS room_consistency (
  listing_id TEXT NOT NULL,
  room_id TEXT NOT NULL,
  room_name TEXT NOT NULL,
  soft_preferences JSONB NOT NULL, -- Array of natural language consistency guidelines
  generated_at TIMESTAMPTZ DEFAULT NOW(),
  PRIMARY KEY (listing_id, room_id),
  FOREIGN KEY (listing_id) REFERENCES listings(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_room_consistency_listing ON room_consistency(listing_id);

COMMENT ON TABLE room_consistency IS 'Room-level consistency preferences generated by E5: soft aesthetic preferences for maintaining consistency across photos of the same room';
COMMENT ON COLUMN room_consistency.soft_preferences IS 'Array of natural language consistency guidelines, e.g., ["Keep north-wall off-white hue within ±3% between shots", "Maintain consistent wood grain direction on floor"]';

