-- Renovation Intelligence Pipeline Tables
-- This migration creates the core tables for the renovation intelligence system

-- Core renovation tiers table
create table
  public.renovation_tiers (
    id bigint generated by default as identity,
    listing_id bigint not null,
    tier_name text not null check (tier_name in ('livable', 'comfortable', 'competitive')),
    work_items jsonb not null default '[]'::jsonb,
    permits jsonb not null default '[]'::jsonb,
    timeline jsonb not null default '[]'::jsonb,
    total_time_months integer,
    total_cost_min integer,
    total_cost_max integer,
    style_prompts jsonb,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint renovation_tiers_pkey primary key (id),
    constraint renovation_tiers_listing_id_tier_name_unique unique (listing_id, tier_name)
  ) tablespace pg_default;

-- Search terms for each tier's work items
create table
  public.renovation_search_terms (
    id bigint generated by default as identity,
    tier_id bigint not null,
    work_item text not null,
    search_terms jsonb not null default '[]'::jsonb,
    created_at timestamp with time zone not null default now(),
    constraint renovation_search_terms_pkey primary key (id),
    constraint renovation_search_terms_tier_id_fkey foreign key (tier_id) references public.renovation_tiers (id) on delete cascade
  ) tablespace pg_default;

-- Search results and credibility scores
create table
  public.renovation_search_results (
    id bigint generated by default as identity,
    search_term_id bigint not null,
    url text not null,
    title text not null,
    content text not null,
    credibility_score decimal(3,2),
    price_data jsonb,
    created_at timestamp with time zone not null default now(),
    constraint renovation_search_results_pkey primary key (id),
    constraint renovation_search_results_search_term_id_fkey foreign key (search_term_id) references public.renovation_search_terms (id) on delete cascade
  ) tablespace pg_default;

-- Indexes for performance
create index idx_renovation_tiers_listing_id on public.renovation_tiers (listing_id);
create index idx_renovation_tiers_tier_name on public.renovation_tiers (tier_name);
create index idx_renovation_search_terms_tier_id on public.renovation_search_terms (tier_id);
create index idx_renovation_search_results_search_term_id on public.renovation_search_results (search_term_id);
create index idx_renovation_search_results_credibility_score on public.renovation_search_results (credibility_score);

-- Comments for documentation
comment on table public.renovation_tiers is 'Stores renovation tier data including work items, permits, timeline, and pricing';
comment on column public.renovation_tiers.tier_name is 'Renovation tier: livable, comfortable, or competitive';
comment on column public.renovation_tiers.work_items is 'JSON array of work items with categories, descriptions, and costs';
comment on column public.renovation_tiers.permits is 'JSON array of permits with explanations and requirements';
comment on column public.renovation_tiers.timeline is 'JSON array of timeline milestones with durations';
comment on column public.renovation_tiers.style_prompts is 'Generated style prompts for image generation';

comment on table public.renovation_search_terms is 'Stores search terms generated for each work item in renovation tiers';
comment on column public.renovation_search_terms.work_item is 'The work item that search terms are generated for';
comment on column public.renovation_search_terms.search_terms is 'JSON array of search terms for market research';

comment on table public.renovation_search_results is 'Stores search results with credibility scores and extracted price data';
comment on column public.renovation_search_results.credibility_score is 'Credibility score from 0.00 to 1.00';
comment on column public.renovation_search_results.price_data is 'Extracted price information from search results';

-- RLS policies
alter table public.renovation_tiers enable row level security;
alter table public.renovation_search_terms enable row level security;
alter table public.renovation_search_results enable row level security;

-- Allow public read access for renovation tiers (for UI display)
create policy "Allow public read access to renovation tiers" on public.renovation_tiers
  for select using (true);

-- Allow service role full access to renovation tables
create policy "Allow service role full access to renovation tiers" on public.renovation_tiers
  for all using (auth.role() = 'service_role');

create policy "Allow service role full access to renovation search terms" on public.renovation_search_terms
  for all using (auth.role() = 'service_role');

create policy "Allow service role full access to renovation search results" on public.renovation_search_results
  for all using (auth.role() = 'service_role');

-- Function to update updated_at timestamp
create or replace function public.update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

-- Trigger to automatically update updated_at
create trigger update_renovation_tiers_updated_at
  before update on public.renovation_tiers
  for each row
  execute function public.update_updated_at_column();
