-- Migration: Add renovation search terms table
-- This table stores search queries generated for each tier and category combination

CREATE TABLE IF NOT EXISTS renovation_search_terms (
  id bigint generated by default as identity,
  listing_id bigint not null,
  tier text not null check (tier in ('estandar', 'optimo', 'plus')),
  category text not null check (category in ('costs', 'durations', 'permits', 'norms')),
  queries_data jsonb not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  
  constraint renovation_search_terms_pkey primary key (id),
  constraint renovation_search_terms_unique unique (listing_id, tier, category)
);

-- Add RLS policies
ALTER TABLE renovation_search_terms ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Allow public read access to renovation search terms" ON renovation_search_terms
  FOR SELECT USING (true);

-- Allow service role full access
CREATE POLICY "Allow service role full access to renovation search terms" ON renovation_search_terms
  FOR ALL USING (auth.role() = 'service_role');

-- Add indexes for performance
CREATE INDEX IF NOT EXISTS idx_renovation_search_terms_listing_id ON renovation_search_terms(listing_id);
CREATE INDEX IF NOT EXISTS idx_renovation_search_terms_tier_category ON renovation_search_terms(tier, category);
CREATE INDEX IF NOT EXISTS idx_renovation_search_terms_created_at ON renovation_search_terms(created_at);

-- Add trigger for updated_at
CREATE OR REPLACE FUNCTION update_renovation_search_terms_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_renovation_search_terms_updated_at
  BEFORE UPDATE ON renovation_search_terms
  FOR EACH ROW
  EXECUTE FUNCTION update_renovation_search_terms_updated_at();
