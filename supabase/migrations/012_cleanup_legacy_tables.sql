-- Migration: Clean up legacy renovation tables
-- Remove old/conflicting tables and keep only the correct ones

-- Drop old tables that are no longer needed
DROP TABLE IF EXISTS renovation_tiers CASCADE;
DROP TABLE IF EXISTS renovation_search_results CASCADE;

-- Drop the old renovation_search_terms table (from migration 008 with 4 categories)
DROP TABLE IF EXISTS renovation_search_terms CASCADE;

-- Drop the research_queries table (from migration 007 - not used)
DROP TABLE IF EXISTS research_queries CASCADE;

-- Drop the search_results_cache table (from migration 007 - not used)
DROP TABLE IF EXISTS search_results_cache CASCADE;

-- Create the correct renovation_research_queries table (this is what our endpoints expect)
CREATE TABLE IF NOT EXISTS renovation_research_queries (
  id bigint generated by default as identity,
  listing_id bigint not null,
  tier text not null check (tier in ('estandar', 'optimo', 'plus')),
  category text not null check (category in ('costs', 'timings', 'permits', 'laws_regulations', 'norms_standards', 'market_practices', 'incentives')),
  queries_data jsonb not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  
  constraint renovation_research_queries_pkey primary key (id),
  constraint renovation_research_queries_unique unique (listing_id, tier, category)
);

-- Add RLS policies
ALTER TABLE renovation_research_queries ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Allow public read access to renovation_research_queries" ON renovation_research_queries
  FOR SELECT USING (true);

-- Allow service role full access
CREATE POLICY "Allow service role full access to renovation_research_queries" ON renovation_research_queries
  FOR ALL USING (auth.role() = 'service_role');

-- Add indexes for performance
CREATE INDEX IF NOT EXISTS idx_renovation_research_queries_listing_id ON renovation_research_queries(listing_id);
CREATE INDEX IF NOT EXISTS idx_renovation_research_queries_tier_category ON renovation_research_queries(tier, category);
CREATE INDEX IF NOT EXISTS idx_renovation_research_queries_created_at ON renovation_research_queries(created_at);

-- Add trigger for updated_at
CREATE OR REPLACE FUNCTION update_renovation_research_queries_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_renovation_research_queries_updated_at
  BEFORE UPDATE ON renovation_research_queries
  FOR EACH ROW
  EXECUTE FUNCTION update_renovation_research_queries_updated_at();
