-- Renovation Intelligence Pipeline Tables
-- This migration creates all the tables needed for the renovation intelligence pipeline

-- Renovation Scope Reports
create table if not exists public.renovation_scope_reports (
  id bigint generated by default as identity,
  listing_id bigint not null,
  report_data jsonb not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint renovation_scope_reports_pkey primary key (id),
  constraint renovation_scope_reports_listing_id_unique unique (listing_id)
) tablespace pg_default;

-- Renovation Research Results
create table if not exists public.renovation_research_results (
  id bigint generated by default as identity,
  listing_id bigint not null,
  category text not null check (category in ('price', 'time', 'permits')),
  report_data jsonb not null,
  created_at timestamp with time zone not null default now(),
  constraint renovation_research_results_pkey primary key (id),
  constraint renovation_research_results_listing_category_unique unique (listing_id, category)
) tablespace pg_default;

