-- Search Results Cache (for caching Google search results)
create table if not exists public.search_results_cache (
  id bigint generated by default as identity,
  listing_id bigint not null,
  query text not null,
  search_results jsonb not null,
  created_at timestamp with time zone not null default now(),
  expires_at timestamp with time zone not null default (now() + interval '7 days'),
  constraint search_results_cache_pkey primary key (id),
  constraint search_results_cache_listing_query_unique unique (listing_id, query)
) tablespace pg_default;

