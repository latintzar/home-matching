#!/usr/bin/env tsx
/**
 * Run migration 035: Add allocentric layout fields to room_analyses table
 * 
 * This script executes the migration SQL statements individually using Supabase client.
 */

import { createClient } from '@supabase/supabase-js';
import * as dotenv from 'dotenv';
import { resolve } from 'path';

// Load environment variables
// Recipient configuration is supplied by tools/runtime-env.py.
const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SUPABASE_SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!SUPABASE_URL || !SUPABASE_SERVICE_KEY) {
  console.error('❌ Missing required environment variables:');
  console.error('   NEXT_PUBLIC_SUPABASE_URL:', SUPABASE_URL ? '✅' : '❌');
  console.error('   SUPABASE_SERVICE_ROLE_KEY:', SUPABASE_SERVICE_KEY ? '✅' : '❌');
  process.exit(1);
}

const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY);

async function runMigration() {
  console.log('🚀 Running migration 035: Add allocentric layout fields...\n');

  const statements = [
    // Add columns
    `ALTER TABLE room_analyses ADD COLUMN IF NOT EXISTS layout_allocentric JSONB;`,
    `ALTER TABLE room_analyses ADD COLUMN IF NOT EXISTS whole_home_summary JSONB;`,
    `ALTER TABLE room_analyses ADD COLUMN IF NOT EXISTS room_layout_json JSONB;`,
    `ALTER TABLE room_analyses ADD COLUMN IF NOT EXISTS unified_home_layout_json JSONB;`,
    
    // Add comments
    `COMMENT ON COLUMN room_analyses.layout_allocentric IS 'Phase 1: Array of RoomLayoutAllocentric - allocentric layouts (structured + expressive narrative) generated by Room-by-Room Analysis';`,
    `COMMENT ON COLUMN room_analyses.whole_home_summary IS 'Phase 1: WholeHomeSummary - lightweight whole-home spatial summary generated from room layouts';`,
    `COMMENT ON COLUMN room_analyses.room_layout_json IS 'Legacy: Per-room layouts from F1 (optional, for backward compatibility)';`,
    `COMMENT ON COLUMN room_analyses.unified_home_layout_json IS 'Legacy: Unified home layout from F2 (optional, for backward compatibility)';`,
  ];

  try {
    // Execute each statement using RPC (if available) or direct query
    // Note: Supabase JS client doesn't support arbitrary SQL execution directly
    // We'll need to use the REST API or provide manual instructions
    
    console.log('⚠️  Supabase JS client cannot execute arbitrary SQL directly.');
    console.log('📋 Please run this migration manually in Supabase SQL Editor:\n');
    console.log('─'.repeat(80));
    console.log('-- Migration 035: Add allocentric layout fields');
    console.log('─'.repeat(80));
    statements.forEach((stmt, i) => {
      console.log(`\n-- Statement ${i + 1}:`);
      console.log(stmt);
    });
    console.log('\n' + '─'.repeat(80));
    console.log('\n✅ Copy the SQL above and run it in Supabase Dashboard → SQL Editor');
    console.log('   URL: https://supabase.com/dashboard/project/' + SUPABASE_URL.split('//')[1].split('.')[0] + '/sql');
    
    // Try to verify the migration by checking if columns exist
    console.log('\n🔍 Verifying migration status...');
    const { data: tableInfo, error: checkError } = await supabase
      .from('room_analyses')
      .select('*')
      .limit(0);
    
    if (checkError) {
      console.error('❌ Error checking table:', checkError.message);
      console.log('\n💡 The table might not exist yet. Run the migration SQL above first.');
    } else {
      console.log('✅ room_analyses table exists');
      console.log('💡 After running the migration, verify columns exist with:');
      console.log('   SELECT column_name FROM information_schema.columns WHERE table_name = \'room_analyses\';');
    }
    
  } catch (err: any) {
    console.error('❌ Migration script error:', err.message);
    process.exit(1);
  }
}

runMigration();
