    "005_after_photos_table.sql", "006_user_profiles_auth.sql", "@merged-profile",
    "008_create_text_analysis_results_table.sql", "013_intake_delivery_preferences.sql",
    "014_architecture_improvement_tables.sql", "018_agents_table.sql",
    "020_vibe_check_tables.sql", "021_daily_recommendations.sql",
    "048_raw_listings.sql", "049_add_agent_notes_to_listings.sql",
    "050_add_reference_number_to_listings.sql", "051_add_idealista_filters.sql",
